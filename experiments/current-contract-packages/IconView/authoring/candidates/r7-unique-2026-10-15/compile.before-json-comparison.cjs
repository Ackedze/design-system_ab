const fs = require('node:fs'), crypto = require('node:crypto'), assert = require('node:assert/strict');
const path = require('node:path');
const D = __dirname, P = path.resolve(D, '../../../..');
const read = f => JSON.parse(fs.readFileSync(f, 'utf8'));
const pin = f => { const b = fs.readFileSync(f); return { path: f, sha256: crypto.createHash('sha256').update(b).digest('hex'), bytes: b.length }; };
const save = (n, v) => fs.writeFileSync(path.join(D, n), JSON.stringify(v) + '\n', { flag: 'wx' });
async function main() {
  const [corePath, coreSha] = process.argv.slice(2);
  assert(corePath && /^[a-f0-9]{64}$/.test(coreSha || ''), 'Pass the explicitly accepted immutable core path and SHA');
  const corePin = pin(corePath); assert.equal(corePin.sha256, coreSha);
  const c = require(corePath), manual = read(path.join(D, 'contract.manual.json'));
  const priorRoot = path.join(P, 'IconView/authoring/candidates/r7-preparation-2026-10-15');
  const prior = read(path.join(priorRoot, 'component-contract.v2.json'));
  const zipPath = path.join(P, 'IconView.r6.candidate.component-contract.zip');
  assert.equal(pin(zipPath).sha256, '4ae85e1d960eac7b4df050ab21ab09a746635f49d901aca2dc55fca62fb79197');
  const entries = await c.readZip(new Uint8Array(fs.readFileSync(zipPath)));
  const files = entries.filter(e => e.name.endsWith('.json')).map(e => ({ name: e.name, text: c.zipEntryText(e) }));
  const imported = c.importWorkspace(files, manual.component.contractId);
  const bundle = c.buildExportBundle(manual, imported.variantEvidence, imported.dependencyContracts);
  save('validation-report.json', bundle.validation);
  assert(bundle.validation.valid, JSON.stringify(bundle.validation));
  assert.equal(bundle.compiled.rules.length, 77); assert.equal(bundle.compiled.nonExecutableRules.length, 8);
  const normalize = r => { const x = structuredClone(r); delete x.source.checksum; if (/-addon-(shape|border)-circle/.test(x.ruleId)) delete x.presentation.title; return x; };
  assert.deepEqual(bundle.compiled.rules.map(normalize), prior.rules.map(normalize));
  assert.deepEqual(bundle.compiled.facts, prior.facts);
  const zip = c.buildAuthoringZip(bundle, files);
  const reopenedEntries = await c.readZip(zip);
  const reopened = c.importWorkspace(reopenedEntries.filter(e => e.name.endsWith('.json')).map(e => ({ name: e.name, text: c.zipEntryText(e) })), manual.component.contractId);
  assert.deepEqual(reopened.manual, manual);
  assert.deepEqual(reopened.variantEvidence, imported.variantEvidence);
  assert.deepEqual(c.buildExportBundle(reopened.manual, reopened.variantEvidence, reopened.dependencyContracts).compiled, bundle.compiled);
  save('component-contract.v2.json', bundle.compiled);
  const output = path.join(D, 'IconView.r7.candidate.component-contract.zip');
  fs.writeFileSync(output, zip, { flag: 'wx' });
  assert.deepEqual(pin(corePath), corePin);
  save('technical-report.json', { status: 'PASS_PRIVATE_CORE_ROUNDTRIP', core: corePin, sourceZip: pin(zipPath), manual: pin(path.join(D, 'contract.manual.json')), compiled: pin(path.join(D, 'component-contract.v2.json')), zip: pin(output), manualSourceHash: c.stableHash(manual), compiledHash: c.stableHash(bundle.compiled), checks: { manualRules: manual.rules.length, active: manual.rules.filter(r => r.status !== 'deprecated').length, assertions: 77, nonExecutableRules: 8, priorExecutableSemanticsPreserved: 77, fullFactsPreserved: true, zipReopen: 'PASS' }, sharedSourceBuildWrites: 0, rootZipWrites: 0, native: 'NOT_RUN_USER_ONLY', registry: 'PENDING', Ready: false });
  console.log(JSON.stringify({ status: 'PASS_PRIVATE_CORE_ROUNDTRIP', assertions: 77, nonExecutableRules: 8, zip: output }));
}
main().catch(e => { save('FAILURE-' + Date.now() + '.json', { message: e.message, stack: e.stack, sharedSourceBuildWrites: 0, rootZipWrites: 0 }); console.error(e.stack); process.exitCode = 1; });
